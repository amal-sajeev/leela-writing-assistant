import process from "node:process";
import esbuild from "esbuild";
import builtins from "builtin-modules";
import { installBuild, describeTarget } from "./scripts/vault-install.mjs";

const production = process.argv.includes("production");

const banner = `/*
This file is generated by esbuild. Edit the TypeScript sources in src/ instead.
*/
`;

/**
 * Obsidian provides these at runtime. Bundling them would break the plugin.
 */
const external = [
  "obsidian",
  "electron",
  "@codemirror/autocomplete",
  "@codemirror/collab",
  "@codemirror/commands",
  "@codemirror/language",
  "@codemirror/lint",
  "@codemirror/search",
  "@codemirror/state",
  "@codemirror/view",
  "@lezer/common",
  "@lezer/highlight",
  "@lezer/lr",
  ...builtins,
];

/** Copies the built plugin into a vault after every successful build. */
const vaultInstallPlugin = {
  name: "vault-install",
  setup(build) {
    build.onEnd(async (result) => {
      if (result.errors.length > 0) return;
      const installed = await installBuild({ quiet: true });
      if (installed) console.log(`[lyra] installed to ${installed}`);
    });
  },
};

const context = await esbuild.context({
  entryPoints: ["src/main.ts"],
  bundle: true,
  external,
  format: "cjs",
  target: "es2022",
  platform: "browser",
  loader: { ".webp": "dataurl" },
  logLevel: "info",
  sourcemap: production ? false : "inline",
  treeShaking: true,
  minify: production,
  outfile: "main.js",
  banner: { js: banner },
  plugins: production ? [] : [vaultInstallPlugin],
});

if (production) {
  await context.rebuild();
  await context.dispose();
  const installed = await installBuild({ quiet: true });
  if (installed) console.log(`[lyra] installed to ${installed}`);
} else {
  console.log(`[lyra] watching. Install target: ${await describeTarget()}`);
  await context.watch();
}
